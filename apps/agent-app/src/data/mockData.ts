// Track used cover images to ensure uniqueness
const usedCoverImages = new Set<number>();

// Helper to generate varied image arrays with different lengths and UNIQUE covers
const generatePropertyImages = (seed: number, minImages = 3, maxImages = 12): string[] => {
  // Find a unique cover image that hasn't been used
  let coverIndex = seed % allImages.length;
  while (usedCoverImages.has(coverIndex) && usedCoverImages.size < allImages.length) {
    coverIndex = (coverIndex + 1) % allImages.length;
  }
  usedCoverImages.add(coverIndex);
  
  // Start with the unique cover image
  const coverImage = allImages[coverIndex];
  
  // Use seed to deterministically shuffle remaining images (excluding cover)
  const remainingImages = allImages.filter((_, idx) => idx !== coverIndex);
  const shuffled = [...remainingImages].sort((a, b) => {
    const hashA = (seed * 31 + remainingImages.indexOf(a)) % 100;
    const hashB = (seed * 31 + remainingImages.indexOf(b)) % 100;
    return hashA - hashB;
  });
  
  // Determine count based on seed
  const count = minImages + (seed % (maxImages - minImages + 1));
  
  // Build images array starting with unique cover
  const images: string[] = [coverImage];
  for (let i = 0; i < count - 1; i++) {
    images.push(shuffled[i % shuffled.length]);
  }
  
  return images;
};

